%aggregate_datasets
d=dir;
for tp=1:2
    for es=[0 .2 .5 .8 1.2]
        dataset_information=[];
        participant_information=[];
        data=[];
        for idx=1:100
            if tp==1
                load([d(1).folder,sprintf('/datasets/PI/PI_Threshold_%1.1f_120_150_%i.mat',es,idx)])
            else
                load([d(1).folder,sprintf('/datasets/PI/PI_Slope_%1.1f_120_150_%i.mat',es,idx)])
            end
            dataset_information=[dataset_information; ...
                tp es idx ...
                dataset.mu_alpha_int dataset.mu_beta_int dataset.mu_lambda_int...
                dataset.mu_alpha_effect dataset.mu_beta_effect...
                dataset.tau_b_alpha_int dataset.tau_b_beta_int dataset.tau_b_lambda_int ...
                dataset.tau_b_alpha_effect dataset.tau_b_beta_effect ...
                dataset.tau_w_alpha_int dataset.tau_w_beta_int dataset.tau_w_lambda_int ...
                ];
            
            for p=1:120
                participant_information(size(participant_information,1)+1 ,:)=[tp es idx p ...
                    dataset.participant(p).alpha_control dataset.participant(p).beta_control dataset.participant(p).lambda_control ...
                    dataset.participant(p).alpha_treatment dataset.participant(p).beta_treatment dataset.participant(p).lambda_treatment...
                    dataset.participant(p).alpha_estimate_control(30) dataset.participant(p).alpha_se_control(30) dataset.participant(p).beta_estimate_control(30) dataset.participant(p).beta_se_control(30) ...
                    dataset.participant(p).alpha_estimate_treatment(30) dataset.participant(p).alpha_se_treatment(30) dataset.participant(p).beta_estimate_treatment(30) dataset.participant(p).beta_se_treatment(30) ...
                    dataset.participant(p).alpha_estimate_control(60) dataset.participant(p).alpha_se_control(60) dataset.participant(p).beta_estimate_control(60) dataset.participant(p).beta_se_control(60) ...
                    dataset.participant(p).alpha_estimate_treatment(60) dataset.participant(p).alpha_se_treatment(60) dataset.participant(p).beta_estimate_treatment(60) dataset.participant(p).beta_se_treatment(60) ...
                    dataset.participant(p).alpha_estimate_control(90) dataset.participant(p).alpha_se_control(90) dataset.participant(p).beta_estimate_control(90) dataset.participant(p).beta_se_control(90) ...
                    dataset.participant(p).alpha_estimate_treatment(90) dataset.participant(p).alpha_se_treatment(90) dataset.participant(p).beta_estimate_treatment(90) dataset.participant(p).beta_se_treatment(90) ...
                    ];
                data=[data; ...
                    repmat([tp es idx p 0],150,1) dataset.participant(p).stimuli_control dataset.participant(p).response_control; ...
                    repmat([tp es idx p 1],150,1) dataset.participant(p).stimuli_treatment dataset.participant(p).response_treatment
                    ];
            end
        end
        participant_information=array2table(participant_information,'VariableNames',{'target_parameter','effect_size','dataset_idx', 'participant_idx' ...
                    'alpha_control' 'beta_control' 'lambda_control' 'alpha_treatment' 'beta_treatment' 'lambda_treatment'...
                    'alpha_estimate_control_30' 'alpha_se_control_30' 'beta_estimate_control_30' 'beta_se_control_30' ...
                    'alpha_estimate_treatment_30' 'alpha_se_treatment_30' 'beta_estimate_treatment_30' 'beta_se_treatment_30' ...
                    'alpha_estimate_control_60' 'alpha_se_control_60' 'beta_estimate_control_60' 'beta_se_control_60' ...
                    'alpha_estimate_treatment_60' 'alpha_se_treatment_60' 'beta_estimate_treatment_60' 'beta_se_treatment_60' ...
                    'alpha_estimate_control_90' 'alpha_se_control_90' 'beta_estimate_control_90' 'beta_se_control_90' ...
                    'alpha_estimate_treatment_90' 'alpha_se_treatment_90' 'beta_estimate_treatment_90' 'beta_se_treatment_90' ...
                    });
        dataset_information=array2table(dataset_information,'VariableNames',{'target_parameter','effect_size','dataset_idx','mu_alpha_int','mu_beta_int','mu_lambda_int'...
                'mu_alpha_effect','mu_beta_effect','tau_b_alpha_int','tau_b_beta_int','tau_b_lambda_int','tau_b_alpha_effect','tau_b_beta_effect','tau_w_alpha_int','tau_w_beta_int','tau_w_lambda_int'});
        data=array2table(data,'VariableNames',{'target_parameter','effect_size','dataset_idx', 'participant_idx' 'condition_is_treatment' 'stimulus' 'response'});
        if tp==1
            writetable(dataset_information,sprintf('Threshold_%1.1f_120_150_dataset_info.csv',es))
            writetable(participant_information,sprintf('Threshold_%1.1f_120_150_ppt_info.csv',es))
            writetable(data,sprintf('Threshold_%1.1f_120_150_data.csv',es))
        else
            writetable(dataset_information,sprintf('Slope_%1.1f_120_150_dataset_info.csv',es))
            writetable(participant_information,sprintf('Slope_%1.1f_120_150_ppt_info.csv',es))
            writetable(data,sprintf('Slope_%1.1f_120_150_data.csv',es))
        end
    end
end

